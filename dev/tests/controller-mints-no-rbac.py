# Non-vacuity floors, set well under the real corpus (4 roles, 22 rules, 28 markers) so an ordinary
# mutation lands on the property it targets rather than tripping vacuity first.
MIN_ROLES = 3
MIN_RULES = 15
MIN_MARKERS = 20

DOC_SPLIT = re.compile(r"^---[ \t]*$", re.M)
RBAC_KIND = re.compile(
    r"^kind:[ \t]*(Role|ClusterRole|RoleBinding|ClusterRoleBinding)[ \t]*$", re.M
)
MARKER = re.compile(r"^[ \t]*//[ \t]*\+kubebuilder:rbac:(\S+)[ \t]*$")
# `resourceNames` and the fields below are read but not modelled; anything else is a marker shape
# this check does not understand, and it says so rather than dropping it.
KNOWN_MARKER_FIELDS = frozenset({"groups", "resources", "verbs", "resourceNames"})
GO_RBAC_IMPORT = re.compile(r'"k8s\.io/api/rbac/v\w+"')


class Rule(NamedTuple):
    """One RBAC rule, from either artifact. A marker is a rule; that is the whole trick."""

    where: str
    groups: tuple[str, ...]
    resources: tuple[str, ...]
    verbs: tuple[str, ...]

    def triples(self) -> set[tuple[str, str, str]]:
        return {(g, r, v) for g in self.groups for r in self.resources for v in self.verbs}


class Corpus(NamedTuple):
    rules: list[Rule]  # every rule in every Role/ClusterRole under config/
    generated: list[Rule]  # just `manager-role`'s
    defined: set[tuple[str, str]]  # (kind, name) of every role the corpus defines
    bindings: list[tuple[str, str, str]]  # (where, roleRef kind, roleRef name)
    unparsed: list[str]  # documents this check could not read; a finding, never a skip


def _documents(text: str) -> list[tuple[int, str]]:
    return list(enumerate(DOC_SPLIT.split(text)))


def _strings(value) -> tuple[str, ...]:
    """A YAML list of scalars as a tuple of strings. `- ` with nothing after it parses to None."""
    if value is None:
        return ()
    if not isinstance(value, list):
        return (str(value),)
    return tuple("" if v is None else str(v) for v in value)


def parse_rbac(texts: dict[str, str]) -> Corpus:
    """Every RBAC document in the YAML corpus, as rules, role identities and bindings.

    Documents are PRE-FILTERED by a top-level `kind:` before the strict parser sees them. That is
    not an optimisation: `config/` also holds CRDs and a ValidatingAdmissionPolicy whose CEL carries
    flow collections, which `yamlsubset` refuses by design, and handing it those would turn every
    run into a parse error about a file this check has no opinion on.
    """
    rules: list[Rule] = []
    generated: list[Rule] = []
    defined: set[tuple[str, str]] = set()
    bindings: list[tuple[str, str, str]] = []
    unparsed: list[str] = []

    for rel in sorted(texts):
        if not rel.endswith((".yaml", ".yml")):
            continue
        for n, doc in _documents(texts[rel]):
            if not RBAC_KIND.search(doc):
                continue
            try:
                obj = load_corpus(doc)
            except CorpusSyntaxError as exc:
                unparsed.append(
                    f"{rel} document {n} is an RBAC document this check cannot parse ({exc}). A "
                    f"document that cannot be read cannot be cleared, and clearing it by skipping "
                    f"it is how a check reports a pass over the one grant nobody could see."
                )
                continue
            kind = obj.get("kind")
            name = str((obj.get("metadata") or {}).get("name") or "(unnamed)")
            where = f"{rel} {kind}/{name}"

            if kind in ("Role", "ClusterRole"):
                defined.add((str(kind), name))
                if obj.get("aggregationRule") is not None:
                    unparsed.append(
                        f"{where} carries an `aggregationRule`. Its rules are filled in at runtime "
                        f"by the controller-manager from whatever ClusterRoles match the selector, "
                        f"so the `rules:` this check parses is not the authority the role confers "
                        f"-- an empty list here would read as 'grants nothing' and be wrong."
                    )
                for i, rule in enumerate(obj.get("rules") or []):
                    if not isinstance(rule, dict):
                        unparsed.append(f"{where} rule {i} is not a mapping: {rule!r}")
                        continue
                    if rule.get("nonResourceURLs") is not None:
                        unparsed.append(
                            f"{where} rule {i} grants `nonResourceURLs`, which this check does not "
                            f"model. A URL grant cannot reach an RBAC object, but the rule is now "
                            f"outside the parse and property 7 would silently disagree about it."
                        )
                    parsed = Rule(
                        f"{where} rule {i}",
                        _strings(rule.get("apiGroups")),
                        _strings(rule.get("resources")),
                        _strings(rule.get("verbs")),
                    )
                    rules.append(parsed)
                    if kind == "ClusterRole" and name == GENERATED_ROLE:
                        generated.append(parsed)
            else:
                ref = obj.get("roleRef") or {}
                bindings.append(
                    (where, str(ref.get("kind") or "(none)"), str(ref.get("name") or "(none)"))
                )

    return Corpus(rules, generated, defined, bindings, unparsed)


def parse_markers(texts: dict[str, str]) -> tuple[list[Rule], list[str]]:
    """Every `+kubebuilder:rbac` marker in the shipped Go source, as rules.

    `_test.go` is excluded because controller-gen's `paths="./..."` loads packages without their
    test files, so a marker there renders nothing. `resourceNames=` is read and dropped: it only
    ever NARROWS a rule, so ignoring it can make this check stricter and never laxer.
    """
    rules: list[Rule] = []
    unparsed: list[str] = []
    for rel in sorted(texts):
        if not rel.endswith(".go") or rel.endswith("_test.go"):
            continue
        for line_no, line in enumerate(texts[rel].splitlines(), 1):
            m = MARKER.match(line)
            if not m:
                continue
            where = f"{rel}:{line_no} +kubebuilder:rbac"
            fields: dict[str, str] = {}
            for field in m.group(1).split(","):
                key, sep, value = field.partition("=")
                if not sep:
                    unparsed.append(f"{where} has a field with no `=`: {field!r}")
                    continue
                fields[key] = value
            unknown = sorted(set(fields) - KNOWN_MARKER_FIELDS)
            if unknown:
                unparsed.append(
                    f"{where} carries marker field(s) {unknown} this check does not model, so the "
                    f"rule controller-gen renders from it is not the rule scanned here. "
                    f"`namespace=` in particular emits a namespaced Role into a different file "
                    f"entirely, and property 7 would report the whole marker as un-rendered."
                )
            rules.append(
                Rule(
                    where,
                    tuple(g.strip('"') for g in fields.get("groups", "").split(";")),
                    tuple(r.strip('"') for r in fields.get("resources", "").split(";")),
                    tuple(v.strip('"') for v in fields.get("verbs", "").split(";")),
                )
            )
    return rules, unparsed


def scan(rules: list[Rule]) -> list[str]:
    """Properties 2 through 6, over one rule at a time. The same scanner reads both artifacts."""
    findings: list[str] = []
    for rule in rules:
        # --- 4. wildcards, one finding per position ------------------------------------------
        if WILDCARD in rule.groups:
            findings.append(
                f"{rule.where} {SIG_WILD_GROUPS}. `*` includes {RBAC_GROUP}, so the rule grants "
                f"its verbs over RBAC itself while property 2's group scan finds nothing to name."
            )
        if WILDCARD in rule.resources:
            findings.append(
                f"{rule.where} {SIG_WILD_RESOURCES}. `*` includes `rolebindings` in whatever "
                f"group the rule names, and every resource that group grows next."
            )
        if WILDCARD in rule.verbs:
            findings.append(
                f"{rule.where} {SIG_WILD_VERBS}. `*` includes `escalate`, `bind` and "
                f"`impersonate`, none of which anybody wrote down."
            )

        for group, resource, verb in sorted(rule.triples()):
            base, slash, _sub = resource.partition("/")
            named = f"{rule.where} grants {verb!r} on {resource!r}"

            # --- 6. the three named escalation verbs, wherever they appear -------------------
            if verb in ESCALATION_VERBS:
                findings.append(
                    f"{named}: {SIG_ESCALATION}. `escalate` lifts the API server's own "
                    f"escalation-prevention check, `bind` confers any Role the holder can name, "
                    f"and `impersonate` is every identity in the cluster at once ([[LSN-004]])."
                )
                continue

            # --- 5. the allow-list, which is the bound underneath 4 and 6 --------------------
            if verb != WILDCARD and verb not in ORDINARY_VERBS:
                findings.append(
                    f"{named}: {SIG_UNLISTED} ({'/'.join(sorted(ORDINARY_VERBS))}). 09 §11.4 makes "
                    f"this an allow-list rather than a deny-list of writes precisely so a verb "
                    f"nobody anticipated is a finding on the day it arrives."
                )
                continue

            # --- 2. no verb on any RBAC resource, reads included -----------------------------
            if group == RBAC_GROUP or base in RBAC_RESOURCES:
                findings.append(
                    f"{named} in API group {group or '(core)'!r}: {SIG_RBAC}, reads included -- "
                    f"the 'beyond `get;list;watch`' clause attaches to ServiceAccounts alone. A "
                    f"controller that can write RBAC can grant an agent whatever it likes at "
                    f"runtime, and no check of the rendered templates would ever see it."
                )
                continue

            # --- 3. identity resources, read-only, subresources untouchable ------------------
            if base in IDENTITY_RESOURCES:
                if slash:
                    findings.append(
                        f"{named}: {SIG_SUBRESOURCE}. `serviceaccounts/token` returns a bearer "
                        f"token for that SA and `certificatesigningrequests/approval` signs a "
                        f"client certificate; either one is the credential itself, not a "
                        f"reference to it."
                    )
                elif verb not in READ_VERBS:
                    findings.append(
                        f"{named}: {SIG_IDENTITY} -- {IDENTITY_RESOURCES[base]}. 08 §2.7's 'May "
                        f"not' list names ServiceAccount alongside the four RBAC kinds, because "
                        f"the two halves of minting authority are the identity and the grant."
                    )
    return findings


def check(rbac_texts: dict[str, str], go_texts: dict[str, str], probe_doc: str) -> list[str]:
    corpus = parse_rbac(rbac_texts)
    markers, marker_errors = parse_markers(go_texts)

    # --- 1. non-vacuity ------------------------------------------------------------------------
    vacuous: list[str] = []
    roles = len({name for _kind, name in corpus.defined})
    if roles < MIN_ROLES:
        vacuous.append(
            f"VACUOUS: {CONFIG_TREE}/ yielded {roles} Role/ClusterRole document(s); there were 4 "
            f"when this was written. Every property below is a scan, and a scan over an empty "
            f"corpus is indistinguishable from a control plane that grants nothing."
        )
    if len(corpus.rules) < MIN_RULES:
        vacuous.append(
            f"VACUOUS: {CONFIG_TREE}/ yielded {len(corpus.rules)} rule(s), under the floor of "
            f"{MIN_RULES}. Either the roles shrank by two thirds or the rule scan stopped seeing "
            f"them, and those two look identical from a green run."
        )
    if (("ClusterRole", GENERATED_ROLE)) not in corpus.defined:
        vacuous.append(
            f"VACUOUS: no ClusterRole named {GENERATED_ROLE!r} was parsed out of {CONFIG_TREE}/. "
            f"That is the ClusterRole 09 §6 and 08 §7 both name, and property 7 compares it -- and "
            f"only it -- against the markers, so its absence retires two properties in silence."
        )
    if len(markers) < MIN_MARKERS:
        vacuous.append(
            f"VACUOUS: {len(markers)} `+kubebuilder:rbac` marker(s) found under {GO_TREE}/, under "
            f"the floor of {MIN_MARKERS}. The markers are the half a developer edits; with none of "
            f"them read, property 7 would report the whole generated ClusterRole as hand-written."
        )
    probe_corpus = parse_rbac({"(probe)/self-test.yaml": probe_doc})
    probe_found = scan(probe_corpus.rules)
    missing = [s for s in PROBE_SIGNALS if not any(s in f for f in probe_found)]
    if probe_corpus.unparsed or not probe_corpus.rules or missing:
        vacuous.append(
            f"VACUOUS: the rule scanner cleared the probe document. It is nothing but violations "
            f"-- {len(probe_corpus.rules)} rule(s) parsed, {len(probe_found)} finding(s) produced "
            f"-- and it did not produce {missing or 'a parse'}. A scanner that no longer "
            f"recognises an RBAC rule when shown one reports the whole tree clean."
        )
    if vacuous:
        return vacuous

    findings: list[str] = list(corpus.unparsed) + list(marker_errors)

    # --- 2-6, over both artifacts --------------------------------------------------------------
    findings += scan(corpus.rules)
    findings += scan(markers)

    # --- 7. the two artifacts agree, triple for triple -----------------------------------------
    rendered_triples = {t for r in corpus.generated for t in r.triples()}
    marker_triples = {t for r in markers for t in r.triples()}
    for group, resource, verb in sorted(marker_triples - rendered_triples):
        findings.append(
            f"{group or '(core)'}/{resource}:{verb} {SIG_MARKER_ONLY}. `make manifests` was not "
            f"run, so the grant is invisible in every YAML in this branch and lands the moment CI "
            f"regenerates -- in a commit that will look like formatting."
        )
    for group, resource, verb in sorted(rendered_triples - marker_triples):
        findings.append(
            f"{group or '(core)'}/{resource}:{verb} {SIG_RENDER_ONLY}. `config/rbac/role.yaml` is "
            f"generated; a hand-edit either ships un-reviewed or is deleted by the next `make "
            f"manifests`, and neither outcome is the one the editor intended."
        )

    # --- 8. no binding reaches outside the corpus ----------------------------------------------
    for where, ref_kind, ref_name in corpus.bindings:
        if (ref_kind, ref_name) not in corpus.defined:
            findings.append(
                f"{where} roleRef names {ref_kind}/{ref_name}, {SIG_DANGLING_REF}. A binding to a "
                f"built-in -- `cluster-admin`, `edit` -- confers its authority with no rule in "
                f"this tree for any property above to read."
            )

    # --- 9. no shipped Go file constructs an RBAC object ---------------------------------------
    for rel in sorted(go_texts):
        if not rel.endswith(".go") or rel.endswith("_test.go"):
            continue
        if GO_RBAC_IMPORT.search(go_texts[rel]):
            findings.append(
                f"{rel} {SIG_GO_IMPORT}/v1, the typed RBAC API. 08 §2.7: the controller consumes "
                f"identity and never produces it, and the only reason to import this package is "
                f"to build a Role or a RoleBinding. RBAC is the bound; this is the grep half of "
                f"08 §7 that says nobody even tried."
            )

    return findings


def _inputs() -> tuple[dict[str, str], dict[str, str], str]:
    rbac_texts = read_repo_files(REPO, CONFIG_TREE)
    go_texts = {
        rel: text
        for rel, text in read_repo_files(REPO, GO_TREE).items()
        if rel.endswith(".go")
    }
    if not rbac_texts:
        raise SystemExit(f"FAIL: {CONFIG_TREE}/ enumerated no files")
    if not go_texts:
        raise SystemExit(f"FAIL: {GO_TREE}/ enumerated no Go files")
    return rbac_texts, go_texts, PROBE_ROLE


def run() -> int:
    inputs = _inputs()
    findings = check(*inputs)
    if findings:
        print("FAIL: V-CTN-017 -- the control plane's RBAC can mint RBAC", file=sys.stderr)
        for f in findings:
            print(f"  - {f}", file=sys.stderr)
        return 1
    corpus = parse_rbac(inputs[0])
    markers, _ = parse_markers(inputs[1])
    grants = sum(len(r.triples()) for r in corpus.rules)
    print(
        f"PASS: V-CTN-017 (L0) -- {len(corpus.defined)} control-plane Role/ClusterRole(s) under "
        f"{CONFIG_TREE}/, {len(corpus.rules)} rule(s) and {grants} (group, resource, verb) "
        f"grant(s), carry no verb on RBAC objects, no write on an identity resource, no wildcard "
        f"in any position and no escalate/bind/impersonate; {len(markers)} +kubebuilder:rbac "
        f"marker(s) agree with {GENERATED_ROLE} triple for triple; all "
        f"{len(corpus.bindings)} roleRef(s) resolve inside the tree; no shipped Go file imports "
        f"the RBAC API"
    )
    return 0


def _mutate(base: tuple[dict[str, str], dict[str, str], str], index: int, fn):
    out = list(base)
    out[index] = fn(out[index])
    return (out[0], out[1], out[2])


def _edit(path: str, old: str, new: str):
    """A corpus transform that rewrites one occurrence in one file and nothing else.

    A path that is not in the corpus leaves it untouched, which the `args == base` guard below
    scores BROKEN. That is the intended behaviour: a mutation anchored on a file that moved must
    not be reported as a MISS against the property it was aimed at ([[LSN-063]]).
    """

    def apply(corpus: dict[str, str]) -> dict[str, str]:
        out = dict(corpus)
        if path in out:
            out[path] = out[path].replace(old, new, 1)
        return out

    return apply


def _blank(path: str):
    def apply(corpus: dict[str, str]) -> dict[str, str]:
        out = dict(corpus)
        if path in out:
            out[path] = ""
        return out

    return apply


