#!/usr/bin/env python3
"""V-CTN-017 (L0): the controller mints no RBAC -- parsed, not read.

09 §6's catalog line is half check and half instruction: *"The controller mints no RBAC -- parse its
ClusterRole, do not inspect it by eye"*. 08 §7 says the same thing in the same words -- *"assert by
parsing the generated RBAC, not by inspection"*. Both are worth taking literally. `manager-role` is
a hundred and forty lines of indented lists in which one extra four-character resource name reads
exactly like the eleven around it, and the reviewer who approves it has already read four other
files. The property is not that the ClusterRole looks narrow. It is that no rule anywhere in the
control plane's install tree confers the ability to create, modify, bind, or impersonate an RBAC
object -- and that is a parse.

WHY THIS IS THE FIRST DOMINO. Every scope ceiling in this system is a grant the pipeline applied
ahead of time. The reader SA can write nothing; the actor SA can write only its tier's template
inside its scope; both are pre-created, GitOps-managed manifests the controller only ever references
by name (08 §2.7, "it consumes identity; it never produces it"). If the controller could mint a Role
and a RoleBinding, it could grant an agent whatever it liked at runtime and no static check of the
rendered templates would ever see it -- the templates would still be correct, and the authority
would simply not have come from them. `actor-grant-single-sourced.py` would stay green while the
thing it single-sources stopped being the only source. "An agent cannot widen its own authority"
would then hold exactly as long as the controller is neither buggy nor compromised, which is the
assumption 08 §4 explicitly refuses to make.

TWO ARTIFACTS, AND THEIR AGREEMENT IS A PROPERTY OF ITS OWN. `config/rbac/role.yaml` is generated by
controller-gen from the `+kubebuilder:rbac` comments under `k8s-operator/`. The rendered file is what
`kustomize build` installs; the markers are what a developer edits. Asserting over one of them leaves
a hole, and a different hole each way. Over the rendered file alone: a marker added without running
`make manifests` is invisible until CI regenerates, so the grant lands in a commit that touches no
YAML and appears in a later one that touches nothing else. Over the markers alone: a hand-edited
`role.yaml` is invisible, and that is the file that ships. So properties 2 through 6 run over BOTH,
and property 7 asserts the two agree triple for triple -- which catches the stale render on its own,
one commit before the marker becomes real.

READ VERBS ON RBAC ARE NOT PERMITTED, AND THAT IS THE SPEC'S CALL RATHER THAN THIS CHECK'S. 08 §7:
*"Its `ClusterRole` contains no verb on `roles`/`clusterroles`/`rolebindings`/`clusterrolebindings`/
`serviceaccounts` beyond `get;list;watch` on ServiceAccounts"*. The "beyond" clause attaches to
ServiceAccounts alone; the four RBAC kinds get zero verbs, reads included. It is worth being honest
that `get roles` is not by itself an escalation -- it reads authority, it does not confer it -- so
the line is drawn at zero for two reasons better than "reads are scary". First, the controller has
no use for it: no shipped Go file under `k8s-operator/` so much as imports `k8s.io/api/rbac/v1`
(property 9), so a read verb on a Role could only ever be a dead grant, and a dead grant on the
RBAC API group is the one nobody re-reads when it stops being dead. Second, zero is the only bound a
parser can hold without a judgement call: "reads are fine, writes are not" requires the check to
decide which verbs are reads, and 09 §11.4 records what that costs -- a write-verb deny-list once
admitted `impersonate`, which is cluster-admin spelled differently. An empty allow-list has no edge
to get wrong.

A SERVICEACCOUNT IS AN IDENTITY; A ROLEBINDING IS A GRANT. The controller must READ ServiceAccounts.
It stamps `spec.serviceAccountName` onto the two Deployments it renders, and it has to be able to
tell an absent SA from a present one so it can fail closed rather than launch a pod under `default`.
It may not create or modify one: 08 §2.7's "May not" list names ServiceAccount alongside the four
RBAC kinds. An SA on its own confers nothing -- it is a name until a RoleBinding mentions it -- but
the two halves of minting authority are the identity and the grant, and a controller holding one
half is one bug away from the other. `serviceaccounts/token` is not the same question: `create` on
it is the TokenRequest API and it returns a bearer credential for that SA, which is the credential
itself rather than a reference to it. Hence property 3's shape -- the base resource may be read, and
no subresource of it may be touched at all.

WHAT COUNTS AS RBAC-MINTING, ARGUED. `rbac.authorization.k8s.io` is the obvious group and it is not
the whole answer, because none of the three verbs that matter most is a write:

  * `escalate` on `roles`/`clusterroles` lifts the API server's own escalation-prevention check --
    the one thing that stops a holder of `create roles` from writing a Role wider than its own.
  * `bind` grants any Role the holder can name, without needing `escalate` and without needing to
    hold the permissions being bound.
  * `impersonate` on `serviceaccounts`/`users`/`groups` is every identity in the cluster at once. It
    appears on core resources, not on RBAC ones, so a check keyed to the RBAC API group misses it
    entirely.

That is why the verb constraint here is an ALLOW-LIST (09 §11.4, [[LSN-004]]): anything outside
`get/list/watch/create/update/patch/delete/deletecollection` is a finding whether or not anyone
remembered to name it. Properties 4 and 6 exist to attribute the three worst cases by name; property
5 is the bound underneath them, and the three partitions are disjoint so each one is reachable
alone. `certificatesigningrequests/approval` is in scope for the same argument one step out: an
approved CSR is a client certificate, a client certificate carrying `O=system:masters` is
cluster-admin, and the mint is the approval subresource rather than the read.

NINE PROPERTIES.

  1. NON-VACUITY, IN FOUR PARTS. The RBAC corpus parsed to at least three `Role`/`ClusterRole`
     documents and fifteen rules; the generated `manager-role` is among them BY NAME; at least
     twenty `+kubebuilder:rbac` markers were read out of the Go source; and the rule scanner, shown
     a probe document that is nothing but violations, produces every signal it is supposed to.
     Everything below is a scan, and a scan over nothing is the greenest thing in this repo. The
     fourth part is the one that matters most: if the scanner stops recognising an RBAC rule -- a
     renamed field, a parser that returns `None` where it used to return a list -- properties 2
     through 6 go quiet and print a pass ([[LSN-035]], [[LSN-038]]). A role carrying an
     `aggregationRule` also fails here rather than passing: its rules are filled in at runtime by
     the controller-manager, so an empty `rules:` would parse as "grants nothing" and be wrong.
  2. NO VERB ON ANY RBAC RESOURCE. Not `create`, not `bind`, not `get`. Enforced both by API group
     and by resource name, because the group is what the API server matches on and the resource name
     is what survives someone writing the group as `rbac.authorization.k8s.io/v1`.
  3. IDENTITY RESOURCES ARE READ-ONLY, AND THEIR SUBRESOURCES ARE UNTOUCHABLE. `serviceaccounts` and
     `certificatesigningrequests` may carry only `get`/`list`/`watch`; `serviceaccounts/token` and
     `certificatesigningrequests/approval` may carry nothing.
  4. NO WILDCARD, IN ANY OF THE THREE POSITIONS, EACH ITS OWN FINDING. `apiGroups: ["*"]` silently
     includes `rbac.authorization.k8s.io`, so property 2's group scan would find nothing to report
     on a rule that grants everything. `resources: ["*"]` and `verbs: ["*"]` are the same hole one
     column over.
  5. EVERY VERB COMES FROM THE ALLOW-LIST. The bound. `use`, `approve`, `sign`, `attest`, and
     whatever the next API group adds are findings on arrival.
  6. `escalate`, `bind` AND `impersonate` ARE NAMED. A subset of property 5's complement, split out
     so the message says which of the three it is and why it is worse than a write.
  7. THE MARKERS AND THE GENERATED CLUSTERROLE AGREE, TRIPLE FOR TRIPLE, IN BOTH DIRECTIONS. A
     marker-only triple is a `make manifests` that was not run. A rendered-only triple is a
     hand-edit to a generated file, which either ships un-reviewed or is silently deleted by the
     next regeneration.
  8. NO BINDING REACHES A ROLE THIS CHECK DID NOT PARSE. `roleRef: {kind: ClusterRole, name:
     cluster-admin}` hands the controller everything while every property above stays green, because
     there is no rule in the tree to read. Every `roleRef` must resolve inside the corpus.
  9. NO SHIPPED GO FILE IMPORTS `k8s.io/api/rbac/v1`. 08 §7's other half -- *"grep + audit-log check
     that no runtime principal created them"* -- is this, statically. Defense in depth rather than
     the bound: properties 2 through 8 are what make the API server refuse.

WHAT THIS DOES NOT ASSERT, deliberately.

  * That the grants it DOES allow are correctly scoped. `create deployments` cluster-wide is a
    conformance failure under 08 §2.7's normative paragraph and it is a different check's property
    (the G-5 pair). This one is about the RBAC group and the escalation verbs only.
  * The live half. A `ClusterRoleBinding` applied out of band, or an aggregation label pulling the
    controller's SA into `cluster-admin`, is invisible to any parse of the repository. That is
    V-CTN-017's L2 arm -- `kubectl auth can-i` as the controller's SA -- and it is a separate unit.
  * A shipped file building an RBAC object through `unstructured.Unstructured` rather than the typed
    API. Property 9 is the import, which is the signal with no false positives; the four files that
    NAME the RBAC kinds as strings (`internal/broker/classify`, `internal/broker/verify`) are
    classifying inbound envelopes by target kind, and a rule that flagged them would be a rule
    against the classifier existing.

WHAT ALREADY EXISTED, AND WHY THIS IS NOT IT. `invariants-gate.py`'s V-CTN-037 holds TEST-ONLY grants
-- documents carrying `kube-agents/test-only-grant` -- to a similar ceiling, and confines them to
`dev/`. `actor-grant-single-sourced.py` (V-BRK-013) single-sources the AGENT identities in
`k8s-operator/scripts/*.yaml.template` and `examples/gitops-repo/` against 06 §2.2 and §2.2.1.
Neither one reads `k8s-operator/config/`, which is where the control plane's own identities live, so
the operator's ClusterRole was asserted by nobody. The corpus here is therefore exactly the RBAC
documents under `k8s-operator/config/` -- discovered by scanning that tree rather than by naming
`role.yaml` ([[LSN-036]]), because `brake_role.yaml` and `config/router/role.yaml` are hand-written,
arrived after the generated one, and are equally the control plane's authority.

Run:  python3 dev/tests/controller-mints-no-rbac.py
      python3 dev/tests/controller-mints-no-rbac.py --negative-control
"""

